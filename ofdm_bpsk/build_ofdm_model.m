function build_ofdm_model()
% BUILD_OFDM_MODEL Builds the Simulink model for BPSK OFDM using
% ONLY Constant blocks and a MATLAB Function block.

    modelName = 'OFDM_Simulink';

    if bdIsLoaded(modelName)
        close_system(modelName, 0);
    end

    if exist([modelName '.slx'], 'file')
        delete([modelName '.slx']);
    end

    % Create and open model
    new_system(modelName);
    open_system(modelName);

    % Solver configuration: single execution step
    set_param(modelName, ...
        'SolverType', 'Fixed-step', ...
        'Solver', 'FixedStepAuto', ...
        'StopTime', '1');

    % 1. Add Constant block for channel length L
    add_block('simulink/Sources/Constant', [modelName '/Constant'], ...
        'Position', [120, 140, 180, 170], ...
        'Value', '2');

    % 2. Add MATLAB Function block
    add_block('simulink/User-Defined Functions/MATLAB Function', [modelName '/MATLAB Function'], ...
        'Position', [280, 115, 450, 195]);

    % 3. Add Display blocks
    add_block('simulink/Sinks/Display', [modelName '/Display'], ...
        'Position', [560, 60, 850, 100]);
    add_block('simulink/Sinks/Display', [modelName '/Display1'], ...
        'Position', [560, 210, 850, 250]);

    % 4. Add To Workspace blocks
    add_block('simulink/Sinks/To Workspace', [modelName '/To Workspace'], ...
        'Position', [560, 120, 680, 150], ...
        'VariableName', 'ber1', ...
        'SaveFormat', 'Array');
    add_block('simulink/Sinks/To Workspace', [modelName '/To Workspace1'], ...
        'Position', [560, 165, 680, 195], ...
        'VariableName', 'theoretical', ...
        'SaveFormat', 'Array');

    % 5. Connect blocks with lines
    add_line(modelName, 'Constant/1', 'MATLAB Function/1');
    add_line(modelName, 'MATLAB Function/1', 'Display/1');
    add_line(modelName, 'MATLAB Function/1', 'To Workspace/1');
    add_line(modelName, 'MATLAB Function/2', 'Display1/1');
    add_line(modelName, 'MATLAB Function/2', 'To Workspace1/1');

    % 6. Write the exact user code into the MATLAB Function block
    sf = sfroot();
    chart = sf.find('-isa', 'Stateflow.EMChart', 'Path', [modelName '/MATLAB Function']);
    
    ofdm_code = sprintf([...
        'function [ber1, theoretical] = OFDM_BPSK(L)\n\n' ...
        'N = 16;\n' ...
        'Niter = 1e3;\n\n' ...
        'cp = L-1;\n\n' ...
        'snrdb = 0:3:39;\n' ...
        'snrlin = 10.^(snrdb/10);\n' ...
        'n_var = 1./snrlin;\n' ...
        'nstd = 1./sqrt(2*N*snrlin);\n\n' ...
        'ber = zeros(Niter,length(snrdb));\n\n' ...
        'for iter = 1:Niter\n\n' ...
        '    x1 = randi([0,1],1,N);\n' ...
        '    x = 2*x1-1;\n\n' ...
        '    xif = ifft(x,N);\n' ...
        '    xcp = [xif(N-cp+1:N),xif];\n\n' ...
        '    for i = 1:length(snrdb)\n\n' ...
        '        h = complex(randn(1,L),randn(1,L))/sqrt(2*L);\n' ...
        '        hf = fft(h,N);\n\n' ...
        '        noise = complex(randn(1,N+cp),randn(1,N+cp));\n\n' ...
        '        y = filter(h,1,xcp) + noise*nstd(i);\n\n' ...
        '        yrcp = y(cp+1:N+cp);\n' ...
        '        yfrcp = fft(yrcp,N);\n\n' ...
        '        yeq = yfrcp./hf;\n' ...
        '        xdet = real(yeq)>0;\n\n' ...
        '        ber(iter,i) = sum(xdet~=x1)/N;\n\n' ...
        '    end\n' ...
        'end\n\n' ...
        'ber1 = mean(ber,1);\n\n' ...
        'theoretical = 0.5*(1-sqrt(snrlin./(1+snrlin)));\n\n' ...
        'end\n']);

    chart.Script = ofdm_code;

    % Save model
    save_system(modelName);
    disp(['Model ' modelName '.slx created and saved successfully!']);
end
