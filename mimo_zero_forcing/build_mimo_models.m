function build_mimo_models
% Create standalone Simulink models using only the four requested block types.
folder = fileparts(mfilename('fullpath'));
load_system('simulink');
for nt = [2 4]
    model = sprintf('mimo_%dx%d_zf', nt, nt);
    if bdIsLoaded(model), close_system(model, 0); end
    new_system(model);
    set_param(model, 'SolverType', 'Fixed-step', ...
        'Solver', 'FixedStepDiscrete', 'FixedStep', '1', ...
        'StartTime', '0', 'StopTime', '0', ...
        'ReturnWorkspaceOutputs', 'off', 'SaveTime', 'off', ...
        'SaveOutput', 'off', 'SignalLogging', 'off');
    add_block('simulink/Sources/Constant', [model '/N_symbols'], ...
        'Value', '1e6', 'SampleTime', '1', 'Position', [50 75 155 110]);
    add_block('simulink/Sources/Constant', [model '/SNR_dB'], ...
        'Value', '0:5:40', 'SampleTime', '1', 'Position', [50 165 155 200]);
    functionPath = [model '/MIMO_BPSK_Rayleigh_ZF'];
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
        functionPath, 'Position', [265 65 525 295]);
    chart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', functionPath);
    chart.Script = fileread(fullfile(folder, sprintf('zf_sweep_%dx%d.m', nt, nt)));
    suffix = sprintf('%dx%d', nt, nt);
    add_block('simulink/Sinks/Display', [model '/BER_display'], ...
        'Format', 'long', 'Position', [665 40 870 235]);
    add_block('simulink/Sinks/To Workspace', [model '/BER_to_workspace'], ...
        'VariableName', ['ber_' suffix], 'SaveFormat', 'Array', ...
        'Position', [665 270 870 310]);
    add_block('simulink/Sinks/To Workspace', [model '/SNR_to_workspace'], ...
        'VariableName', ['snrdb_' suffix], 'SaveFormat', 'Array', ...
        'Position', [265 365 470 405]);
    add_line(model, 'N_symbols/1', 'MIMO_BPSK_Rayleigh_ZF/1', 'autorouting', 'on');
    add_line(model, 'SNR_dB/1', 'MIMO_BPSK_Rayleigh_ZF/2', 'autorouting', 'on');
    add_line(model, 'MIMO_BPSK_Rayleigh_ZF/1', 'BER_display/1', 'autorouting', 'on');
    add_line(model, 'MIMO_BPSK_Rayleigh_ZF/1', 'BER_to_workspace/1', 'autorouting', 'on');
    add_line(model, 'SNR_dB/1', 'SNR_to_workspace/1', 'autorouting', 'on');
    note = Simulink.Annotation(model, sprintf([...
        '%dx%d MIMO | BPSK | independent Rayleigh fading | Zero Forcing\n' ...
        'One simulation step computes the complete SNR sweep.\n' ...
        'N = symbols per transmit antenna, per SNR. Stop time = 0.\n' ...
        'BER display entries correspond to SNR = 0, 5, ..., 40 dB.'], nt, nt));
    note.Position = [45 445];
    set_param(model, 'ZoomFactor', '100');
    save_system(model, fullfile(folder, [model '.slx']));
    close_system(model, 0);
end
fprintf('Created both models in %s\n', folder);
end
